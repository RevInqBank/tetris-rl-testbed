"""Independent third implementation of the two `wells10` features.

rl added `max_well_depth` and `well_count`, and asked for the same treatment I
gave the original eight: a THIRD implementation written from the prose
definitions alone, so that agreement is not two-of-rl's-own-code agreeing with
itself. rl's own cross-check (numpy reference vs bitboard, 3,000 boards, zero
mismatches) is real but both sides are rl's.

So the loops below are written from `weights/wells10_reference.json`'s
`definition` block ONLY -- not from `rl/features.py`, and not from rl's message.
Plain Python, no numpy, no bitmasks, deliberately the dumbest possible reading
of the prose:

    well cell : empty, and BOTH horizontal neighbours filled. Walls (column -1
                and column 10) count as filled. Identical predicate to
                cumulative_wells -- only the aggregation differs.
    run       : a vertically CONTIGUOUS group of well cells. A filled cell in
                the middle splits it into separate runs.
    max_well_depth : size of the largest run, 0 if there are none.
    well_count     : number of runs of size >= 3. Below the threshold: not
                     counted.
    board     : the visible 20 rows only.

Three comparisons, because each catches something different:
  1. my loops vs rl's 8 HAND-COMPUTED fixtures -- catches a misread of the
     prose. rl flagged `split_well` as the easiest to get wrong (runs are
     contiguous groups, not per-column totals), so that one is decisive.
  2. my loops vs rl's 300 random-board expectations -- catches a rule that
     happens to work on small hand cases.
  3. my loops vs the LIVE rl/features.py -- catches the reference file having
     been generated by code that has since changed.

Also asserted: the wells10 predicate really is the same as cumulative_wells's,
since rl says so in writing and that claim is load-bearing (if they drifted, a
board could have wells by one definition and not the other).

Run:  <ml python> tests/test_wells10_features.py
Owner of the code under test: rl.  This file is checker-owned.
"""

import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
sys.path.insert(0, os.path.join(_ROOT, "rl"))

REF = os.path.join(_ROOT, "weights", "wells10_reference.json")

PASSED, FAILED, SKIPPED = [], [], []


def ok(m):
    PASSED.append(m)
    print("  ok   %s" % m)


def fail(t, m):
    FAILED.append((t, m))
    print("  FAIL [%s] %s" % (t, m))


def skip(t, m):
    SKIPPED.append((t, m))
    print("  SKIP [%s] %s" % (t, m))


# ===========================================================================
# my implementation -- from the prose only
# ===========================================================================

def well_cells(board):
    """Set of (r, c) that are well cells. Walls count as filled."""
    rows = len(board)
    cols = len(board[0]) if rows else 0
    out = set()
    for r in range(rows):
        for c in range(cols):
            if board[r][c]:
                continue                      # must be EMPTY
            left = 1 if c == 0 else board[r][c - 1]      # wall = filled
            right = 1 if c == cols - 1 else board[r][c + 1]
            if left and right:
                out.add((r, c))
    return out


def well_runs(board):
    """Lengths of vertically contiguous runs of well cells.

    Walk each column top to bottom. A well cell extends the current run; ANY
    non-well cell (filled, or empty-but-not-a-well) ends it. That is what
    "a filled cell in the middle splits it into separate runs" means, read
    literally -- the run is a maximal contiguous group, not a per-column total.
    """
    cells = well_cells(board)
    rows = len(board)
    cols = len(board[0]) if rows else 0
    lengths = []
    for c in range(cols):
        run = 0
        for r in range(rows):
            if (r, c) in cells:
                run += 1
            else:
                if run:
                    lengths.append(run)
                run = 0
        if run:
            lengths.append(run)
    return lengths


def my_max_well_depth(board):
    runs = well_runs(board)
    return max(runs) if runs else 0


def my_well_count(board, threshold=3):
    return sum(1 for n in well_runs(board) if n >= threshold)


def my_cumulative_wells(board):
    """cumulative_wells, re-derived here purely so the shared-predicate claim
    can be checked: a well of depth d contributes 1+2+...+d."""
    cells = well_cells(board)
    rows = len(board)
    cols = len(board[0]) if rows else 0
    total = 0
    for c in range(cols):
        depth = 0
        for r in range(rows):
            if (r, c) in cells:
                depth += 1
                total += depth
            else:
                depth = 0
    return total


